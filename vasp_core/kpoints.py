#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""kpoints.py —— KPOINTS 的四种写法：Gamma、Monkhorst-Pack、line-mode、显式点列。

为什么不用 pymatgen 的 Kpoints：
  同上（集群装不动）。这四种覆盖了 95% 的前处理需求；
  能带路径（line-mode）和显式点列是 v1 缺的，v2 补上。

一个容易犯的错：KPOINTS 与 INCAR 的 KSPACING 同时存在时，VASP 用 KPOINTS、
忽略 KSPACING，但不会警告 —— 所以 prep.py 会主动检查并报 ERROR。
"""

from __future__ import annotations

from dataclasses import dataclass, field

from .errors import StructureError


@dataclass
class Kpoints:
    mode: str                                   # gamma / mp / line / explicit
    mesh: list[int] | None = None               # gamma/mp
    segments: list[dict] | None = None          # line: [{"from":[..],"to":[..],"points":N,"label_from":..,"label_to":..}]
    points: list[dict] | None = None            # explicit: [{"coords":[..],"weight":1.0,"label":".."}]
    coord: str = "Reciprocal"                   # Reciprocal / Cartesian
    comment: str = "KPOINTS generated by vasp-prep"

    def as_dict(self) -> dict:
        return {
            "mode": self.mode,
            "mesh": self.mesh,
            "segments": self.segments,
            "points": self.points,
            "coord": self.coord,
            "comment": self.comment,
        }


def _fmt(x: float) -> str:
    s = f"{float(x):.8f}".rstrip("0").rstrip(".")
    return s if s not in ("", "-0") else "0"


def _vec(v, what: str) -> list[float]:
    if not (isinstance(v, (list, tuple)) and len(v) == 3):
        raise StructureError(f"{what} 需要 3 个数，收到 {v!r}")
    try:
        return [float(x) for x in v]
    except (TypeError, ValueError) as exc:
        raise StructureError(f"{what} 里有非数字：{v!r}") from exc


def from_recipe(cfg: dict | None) -> Kpoints | None:
    """把配方里的 kpoints 段翻译成 Kpoints；None 表示不写 KPOINTS（用 KSPACING）。"""
    if cfg is None:
        return None
    if not isinstance(cfg, dict):
        raise StructureError(f"kpoints 必须是对象或 null，收到 {type(cfg).__name__}")
    mode = str(cfg.get("mode", "gamma")).lower()
    coord = str(cfg.get("coord", "Reciprocal"))
    if coord.lower().startswith("c"):
        coord = "Cartesian"
    else:
        coord = "Reciprocal"
    comment = str(cfg.get("comment") or "KPOINTS generated by vasp-prep")

    if mode in ("gamma", "mp"):
        mesh = cfg.get("mesh") or [1, 1, 1]
        if not (isinstance(mesh, (list, tuple)) and len(mesh) == 3):
            raise StructureError(f"{mode} 的 mesh 需要 3 个整数，收到 {mesh!r}")
        m = []
        for x in mesh:
            if isinstance(x, bool) or not isinstance(x, int) or x < 1:
                raise StructureError(f"mesh 必须是正整数，收到 {x!r}")
            if x > 64:
                raise StructureError(f"mesh 分量 {x} 太大（>64），检查是不是写错了")
            m.append(x)
        return Kpoints(mode=mode, mesh=m, coord=coord, comment=comment)

    if mode == "line":
        segs = cfg.get("segments") or []
        if not isinstance(segs, list) or not segs:
            raise StructureError("line 模式需要 segments 列表（至少 1 段）")
        norm = []
        for i, s in enumerate(segs, 1):
            if not isinstance(s, dict):
                raise StructureError(f"第 {i} 段不是对象：{s!r}")
            a = _vec(s.get("from"), f"第 {i} 段 from")
            b = _vec(s.get("to"), f"第 {i} 段 to")
            n = s.get("points", cfg.get("points_per_segment", 20))
            if isinstance(n, bool) or not isinstance(n, int) or n < 2:
                raise StructureError(f"第 {i} 段 points 必须是 ≥2 的整数，收到 {n!r}")
            norm.append({
                "from": a, "to": b, "points": n,
                "label_from": s.get("label_from") or "",
                "label_to": s.get("label_to") or "",
            })
        pts = sorted({s["points"] for s in norm})
        if len(pts) > 1:
            raise StructureError(
                f"line 模式要求所有段的 points 相同（VASP 只认一个值），当前有 {pts}"
            )
        return Kpoints(mode="line", segments=norm, coord=coord, comment=comment)

    if mode == "explicit":
        pts = cfg.get("points") or []
        if not isinstance(pts, list) or not pts:
            raise StructureError("explicit 模式需要 points 列表")
        norm = []
        for i, p in enumerate(pts, 1):
            if not isinstance(p, dict):
                raise StructureError(f"第 {i} 个 K 点不是对象：{p!r}")
            c = _vec(p.get("coords"), f"第 {i} 个 K 点 coords")
            w = p.get("weight", 1.0)
            try:
                w = float(w)
            except (TypeError, ValueError) as exc:
                raise StructureError(f"第 {i} 个 K 点 weight 不是数字") from exc
            if w < 0:
                raise StructureError("K 点权重不能为负")
            norm.append({"coords": c, "weight": w, "label": p.get("label") or ""})
        return Kpoints(mode="explicit", points=norm, coord=coord, comment=comment)

    raise StructureError(f"不支持的 kpoints.mode={mode!r}（可用 gamma / mp / line / explicit）")


def render_kpoints(kp: Kpoints) -> str:
    """按 VASP 官方格式写 KPOINTS 文本。"""
    lines: list[str] = [kp.comment]

    if kp.mode in ("gamma", "mp"):
        assert kp.mesh is not None
        lines.append("0")
        lines.append("Gamma" if kp.mode == "gamma" else "Monkhorst-Pack")
        lines.append("  " + "  ".join(str(x) for x in kp.mesh))
        lines.append("  0  0  0")
        return "\n".join(lines) + "\n"

    if kp.mode == "line":
        assert kp.segments is not None
        points = kp.segments[0]["points"]
        lines.append(str(points))
        lines.append("Line-mode")
        lines.append(kp.coord)
        for seg in kp.segments:
            # 每段的起点和终点都写出来；相邻段共享的端点重复出现，VASP 会按顺序连起来
            a, b = seg["from"], seg["to"]
            la, lb = seg["label_from"], seg["label_to"]
            lines.append("  " + "  ".join(_fmt(x) for x in a) + (f"   ! {la}" if la else ""))
            lines.append("  " + "  ".join(_fmt(x) for x in b) + (f"   ! {lb}" if lb else ""))
        return "\n".join(lines) + "\n"

    if kp.mode == "explicit":
        assert kp.points is not None
        lines.append(str(len(kp.points)))
        lines.append(kp.coord)
        for p in kp.points:
            c = p["coords"]
            lines.append(
                "  " + "  ".join(_fmt(x) for x in c) + f"   {_fmt(p['weight'])}"
                + (f"   ! {p['label']}" if p["label"] else "")
            )
        return "\n".join(lines) + "\n"

    raise StructureError(f"内部错误：未知 mode {kp.mode}")


def check_kpoints(kp: Kpoints | None, *, lattice: list[list[float]] | None = None,
                  is_slab: bool | None = None) -> list[dict]:
    """KPOINTS 层面的轻量检查；返回 [{"level","code","message"}]。"""
    out: list[dict] = []
    if kp is None:
        return out
    if kp.mode in ("gamma", "mp"):
        assert kp.mesh is not None
        if max(kp.mesh) >= 30:
            out.append({"level": "WARN", "code": "kmesh-large",
                        "message": f"K 网格 {kp.mesh} 很大，计算量可能爆炸；确认是否必要"})
        if min(kp.mesh) < 1:
            out.append({"level": "ERROR", "code": "kmesh-invalid", "message": "K 网格必须 ≥1"})
    if kp.mode == "line":
        assert kp.segments is not None
        if any(s["points"] < 2 for s in kp.segments):
            out.append({"level": "ERROR", "code": "line-points", "message": "line 模式每段至少 2 个点"})
    if is_slab and kp.mode in ("gamma", "mp") and kp.mesh and kp.mesh[2] != 1:
        out.append({"level": "WARN", "code": "slab-kz",
                    "message": f"表面体系通常 z 方向只取 1 个 K 点，当前 mesh={kp.mesh}"})
    return out
